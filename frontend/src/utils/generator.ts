import type { BedtoolsParams } from '../components/BedtoolsNode';

interface PipelineConfig {
  params: BedtoolsParams;
  queryFile: string;
  targetFile: string;
  outputFile: string;
}

export function generateSnakefile(config: PipelineConfig): string {
  const { params, queryFile, targetFile, outputFile } = config;

  let flagArgs = '';
  if (params.useAsymmetric) {
    flagArgs += `-l ${params.upstream} -r ${params.downstream} `;
    if (params.strandAware) flagArgs += '-sw ';
  } else {
    flagArgs += `-w ${params.windowSize} `;
  }

  if (params.strandMode === 'same') flagArgs += '-sm ';
  if (params.strandMode === 'opposite') flagArgs += '-S ';

  return `# ==========================================
# Generated by SnakeStudio (MIT License)
# Target: Helianthus annuus cis-LncRNA Analysis
# ==========================================

rule all:
    input:
        "${outputFile}"

rule bedtools_cis_window:
    input:
        query="${queryFile}",
        target="${targetFile}"
    output:
        "${outputFile}"
    params:
        flags="${flagArgs.trim()}"
    threads: 2
    message:
        "Scanning cis-targets with flags: {params.flags}"
    shell:
        "bedtools window -a {input.query} -b {input.target} {params.flags} > {output}"
`;
}